import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';

// Local synthetic fixture. The separate DEV preview is checked manually with the QA property.
test('property prices, rules, browser back and batch confirmation retain context',async({page},testInfo)=>{
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 await page.goto('/admin.html?view=properties');
 await expect(page.locator('[data-property-edit="2"]')).toBeVisible();
 await page.locator('[data-property-edit="2"]').click();
 await page.locator('[data-workspace="prices"]').click();
 await expect(page.locator('[data-price-origin]')).toContainText('tabela própria');
 await page.locator('[data-price-month]').fill('2027-02');
 await page.locator('[data-price-month]').dispatchEvent('change');
 await expect(page.locator('[data-price-context-month]')).toContainText('fevereiro de 2027');
 await page.locator('[name="start"]').fill('2027-02-05');
 await page.locator('[name="end"]').fill('2027-02-07');
 await page.locator('[data-selection] [name="value"]').fill('123,00');
 const post=page.waitForRequest(r=>r.method()==='POST'&&r.postDataJSON()?.operation==='save_pricing');
 await page.locator('[data-selection] [type="submit"]').click();
 await expect(page.locator('[data-price-review]')).toBeVisible();
 await page.locator('[data-review-confirm]').click();
 expect((await post).postDataJSON().own_pricing.periods.some(p=>p.cents===12300&&p.start==='2027-02-05'&&p.end==='2027-02-07')).toBe(true);
 await expect(page.locator('[data-price-status]')).toContainText('salva');
 await mkdir('docs/ux/issue-14',{recursive:true});
 await page.locator('.admin-modal').evaluate(element=>element.scrollTop=0);
 await page.screenshot({path:`docs/ux/issue-14/prices-after-${testInfo.project.name}.png`,fullPage:true});
 await page.locator('[data-rules]').click();
 await expect(page.locator('[data-availability-tab="rules"]')).toHaveAttribute('aria-selected','true');
 await page.screenshot({path:`docs/ux/issue-14/rules-after-${testInfo.project.name}.png`,fullPage:true});
 await page.locator('#availability-form .workspace-rule').first().locator('summary').click();
 await page.locator('#availability-form [name="min_nights"]').fill('2');
 page.once('dialog',dialog=>dialog.dismiss());
 await page.locator('#back-property-details').click();
 await expect(page.locator('#availability-form')).toBeVisible();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#back-property-details').click();
 await expect(page.locator('[data-price-month]')).toHaveValue('2027-02');
 await expect(page.locator('[name="start"]')).toHaveValue('2027-02-05');
 await page.goBack();
 await expect(page.locator('[data-workspace="prices"]')).toBeVisible();
 await page.locator('#workspace-close').click();
 await expect(page.locator('#admin-modal')).toBeHidden();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 expect(errors).toEqual([]);
 await page.screenshot({path:`docs/ux/issue-14/properties-after-${testInfo.project.name}.png`,fullPage:true});
});


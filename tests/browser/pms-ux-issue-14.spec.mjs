test('synthetic block and rules save survive reload without touching channel links',async({page})=>{
 const calls=[];page.on('request',request=>{if(request.method()==='POST'){try{calls.push(request.postDataJSON())}catch{}}});
 await page.goto('/admin.html?view=properties');
 await page.locator('[data-property-edit="2"]').click();
 await page.locator('[data-workspace="prices"]').click();
 await page.locator('[data-price-month]').fill('2027-04');
 await page.locator('[data-price-month]').dispatchEvent('change');
 await page.locator('[name="start"]').fill('2027-04-10');
 await page.locator('[name="end"]').fill('2027-04-11');
 await page.locator('[data-block-reason]').fill('Bloqueio QA local');
 await page.locator('[data-block]').click();
 await expect(page.locator('[data-price-review]')).toContainText('Bloqueio QA local');
 await page.locator('[data-review-confirm]').click();
 await expect(page.locator('[data-price-status]')).toContainText('salva');
 await expect(page.locator('[data-price-grid] .price-blocked')).toHaveCount(2);
 await page.locator('[data-price-events] [data-release]').click();
 await expect(page.locator('[data-price-review]')).toContainText('Remover o bloqueio inteiro');
 await page.locator('[data-review-confirm]').click();
 await expect(page.locator('[data-price-grid] .price-blocked')).toHaveCount(0);
 await page.locator('[data-rules]').click();
 await page.locator('#availability-form .workspace-rule').first().locator('summary').click();
 await page.locator('#availability-form [name="min_nights"]').fill('3');
 await page.locator('#availability-form [type="submit"]').click();
 await expect(page.locator('#availability-message')).toContainText('salva');
 await page.reload();
 await page.locator('[data-property-edit="2"]').click();
 await page.locator('[data-workspace="availability"]').click();
 await page.locator('[data-availability-tab="rules"]').click();
 await page.locator('#availability-form .workspace-rule').first().locator('summary').click();
 await expect(page.locator('#availability-form [name="min_nights"]')).toHaveValue('3');
 expect(calls.filter(c=>c.action==='admin_calendar'&&c.operation!=='list')).toHaveLength(0);
});

test('keyboard focus stays in the panel and Escape closes to the invoking property',async({page})=>{
 await page.goto('/admin.html?view=properties');
 const card=page.locator('[data-property-edit="2"]');
 await card.click();
 await page.locator('[data-workspace="prices"]').click();
 await expect(page.locator('.admin-modal .admin-drawer-close')).toBeFocused();
 await page.keyboard.press('Shift+Tab');
 expect(await page.evaluate(()=>document.querySelector('.admin-modal').contains(document.activeElement))).toBe(true);
 await page.keyboard.press('Escape');
 await expect(page.locator('#admin-modal')).toBeHidden();
 await expect(card).toBeFocused();
});
